export const STRINGS: Record<Lang, Strings> = { de, en };

export function detectLang(): Lang {
  const l = (typeof navigator !== 'undefined' && navigator.language) || 'de';
  return l.toLowerCase().startsWith('de') ? 'de' : 'en';
}
